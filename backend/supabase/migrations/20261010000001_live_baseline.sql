-- Baseline for the tables that were created by hand in the live Supabase project
-- before the repo tracked them (marketplace listings, shop owners and their
-- submissions, orders, enquiries). Taken from the live schema dump of
-- 2026-10-13 (backend/supabase/live-schema-2026-10-13.sql), as it stood before
-- 20261011000001 added accounts and shop verification.
--
-- Guarded so it changes nothing on the live database: every table, index,
-- function and trigger is created only if it doesn't exist, RLS is only
-- switched on where it is off, and policies are only added to tables this run
-- created (so it never re-adds a policy that a later fix removed). Grants are
-- left to Supabase's defaults.

-- Tables that already exist before this run; their policies are left alone.
drop table if exists pg_temp.reloop_baseline_existing;
create temp table reloop_baseline_existing as
  select tablename from pg_tables
   where schemaname = 'public'
     and tablename in ('admin_users', 'categories', 'enquiries', 'institution_submissions', 'listings',
                       'orders', 'processing_records', 'shop_owners', 'shop_submissions');

create table if not exists public.admin_users (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null,
  email text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.listings (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category_id bigint references public.categories (id) on delete set null,
  brand text,
  model text,
  condition text not null default 'Used'
    check (condition in ('New', 'Like New', 'Good', 'Used', 'Refurbished', 'For Parts')),
  price numeric(12, 2) not null check (price >= 0),
  stock integer not null default 1 check (stock >= 0),
  image_url text,
  status text not null default 'Active' check (status in ('Active', 'Inactive', 'Sold', 'Out of Stock')),
  featured boolean not null default false,
  purchase_cost numeric(12, 2) check (purchase_cost >= 0),
  processing_cost numeric(12, 2) check (processing_cost >= 0),
  internal_notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  grade text check (grade is null or grade in ('A', 'B', 'C', 'D'))
);
create index if not exists listings_category_idx on public.listings (category_id);
create index if not exists listings_featured_idx on public.listings (featured);
create index if not exists listings_status_idx on public.listings (status);

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings (id) on delete cascade,
  customer_name text not null,
  customer_email text,
  customer_phone text,
  message text,
  status text not null default 'New' check (status in ('New', 'Contacted', 'Closed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists enquiries_listing_idx on public.enquiries (listing_id);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  listing_id bigint references public.listings (id) on delete set null,
  customer_name text not null,
  customer_email text,
  customer_phone text,
  quantity integer not null default 1 check (quantity > 0),
  total_amount numeric(12, 2) check (total_amount >= 0),
  status text not null default 'Pending'
    check (status in ('Pending', 'Confirmed', 'Processing', 'Completed', 'Cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists orders_listing_idx on public.orders (listing_id);

create table if not exists public.institution_submissions (
  id uuid primary key default gen_random_uuid(),
  institution_name text not null,
  contact_name text not null,
  phone text not null,
  email text,
  details jsonb not null default '{}',
  status text not null default 'Pending',
  created_at timestamptz not null default now()
);

-- Shop owners as they were before 20261011000001 added GSTIN and verification.
create table if not exists public.shop_owners (
  id uuid primary key,
  shop_name text not null,
  owner_name text not null,
  email text,
  phone text,
  address text,
  city text default 'Jammu',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint shop_owners_id_auth_user_fkey foreign key (id) references auth.users (id) on delete cascade
);

create table if not exists public.shop_submissions (
  id bigint generated by default as identity primary key,
  shop_owner_id uuid not null references public.shop_owners (id) on delete cascade,
  item_name text not null,
  category_id bigint references public.categories (id) on delete set null,
  brand text,
  model text,
  description text,
  quantity integer not null default 1 check (quantity > 0),
  condition text not null default 'Used'
    check (condition in ('New', 'Like New', 'Good', 'Used', 'Damaged', 'For Parts')),
  asking_price numeric(12, 2) check (asking_price >= 0),
  image_url text,
  status text not null default 'Pending'
    check (status in ('Pending', 'Under Review', 'Contacted', 'Purchased', 'Rejected', 'Processing', 'Completed')),
  purchase_price numeric(12, 2) check (purchase_price >= 0),
  internal_notes text,
  rejection_reason text,
  purchased_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists submissions_category_idx on public.shop_submissions (category_id);
create index if not exists submissions_shop_owner_idx on public.shop_submissions (shop_owner_id);
create index if not exists submissions_status_idx on public.shop_submissions (status);

create table if not exists public.processing_records (
  id bigint generated by default as identity primary key,
  submission_id bigint references public.shop_submissions (id) on delete set null,
  listing_id bigint references public.listings (id) on delete set null,
  process_type text not null check (process_type in
    ('Inspection', 'Repair', 'Refurbishment', 'Cleaning', 'Testing', 'Data Wiping', 'Dismantling', 'Other')),
  description text,
  cost numeric(12, 2) default 0 check (cost >= 0),
  status text not null default 'Pending' check (status in ('Pending', 'In Progress', 'Completed')),
  processed_by uuid references public.admin_users (id) on delete set null,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);
create index if not exists processing_listing_idx on public.processing_records (listing_id);
create index if not exists processing_submission_idx on public.processing_records (submission_id);

-- Functions. The live is_admin() checks admin_users; where an is_admin() already
-- exists (the live one, or the hub's in tests) it is left as it is.
do $$
begin
  if to_regprocedure('public.is_admin()') is null then
    create function public.is_admin() returns boolean
      language sql stable security definer
      set search_path = 'public'
      as $f$
        select exists (
          select 1 from public.admin_users where id = auth.uid() and is_active = true
        );
      $f$;
  end if;

  if to_regprocedure('public.update_updated_at()') is null then
    create function public.update_updated_at() returns trigger
      language plpgsql
      as $f$
      begin
        new.updated_at = now();
        return new;
      end;
      $f$;
  end if;
end $$;

-- updated_at triggers.
do $$
declare
  t text;
begin
  foreach t in array array['enquiries', 'listings', 'orders', 'shop_owners', 'shop_submissions'] loop
    if not exists (
      select 1 from pg_trigger
      where tgname = t || '_updated_at' and tgrelid = ('public.' || t)::regclass and not tgisinternal
    ) then
      execute format(
        'create trigger %I before update on public.%I for each row execute function public.update_updated_at()',
        t || '_updated_at', t
      );
    end if;
  end loop;
end $$;

-- Row Level Security, switched on only where it is off.
do $$
declare
  t text;
begin
  foreach t in array array['admin_users', 'categories', 'enquiries', 'institution_submissions', 'listings',
                           'orders', 'processing_records', 'shop_owners', 'shop_submissions'] loop
    if not (select relrowsecurity from pg_class where oid = ('public.' || t)::regclass) then
      execute format('alter table public.%I enable row level security', t);
    end if;
  end loop;
end $$;

